# 定义学生成绩变量，赋值为75分
grade = 75

# 90分及以上：输出"优秀"
if grade >= 90:
    print("优秀")
# 80-89分：输出"良好"（仅当前面条件不成立时判断）
elif grade >= 80:
    print("良好")
# 60-79分：输出"及格"（仅当前面条件都不成立时判断）
elif grade >= 60:
    print("及格")
# 60分以下：输出"不及格"（仅当前面条件都不成立时执行）
# 在多重判断语句中，当不需要else时，建议在else处输出报错。尽量不要不写else或空着。
else:
    print("不及格")
